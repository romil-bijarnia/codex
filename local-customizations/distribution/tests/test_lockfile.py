"""Offline Cargo.lock merging with real Git and disposable text fixtures."""
from pathlib import Path
import sys
import tomllib
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from lockfile import LockfileMergeConflict, merge_lockfile


WORKSPACE_VERSION = '0.171.0-alpha.11'


def package(name, version, *, source=None, dependencies=(), checksum=None):
    lines = ['[[package]]', f'name = "{name}"', f'version = "{version}"']
    if source is not None:
        lines.append(f'source = "{source}"')
    if checksum is not None:
        lines.append(f'checksum = "{checksum}"')
    if dependencies:
        lines += ['dependencies = [', *(f' "{item}",' for item in dependencies), ']']
    return '\n'.join(lines) + '\n\n'


def lock(*packages):
    return '# This file is automatically generated by Cargo.\nversion = 4\n\n' + ''.join(packages)


class LockfileMergeTests(unittest.TestCase):
    def merge(self, base, custom, upstream, members=('codex-demo',)):
        return merge_lockfile(base, custom, upstream, WORKSPACE_VERSION, members)

    def test_generated_workspace_versions_do_not_override_new_upstream(self):
        base = lock(package('codex-demo', '0.0.0'))
        custom = lock(package('codex-demo', WORKSPACE_VERSION))
        upstream = lock(package('codex-demo', '0.171.0-alpha.12'))
        self.assertEqual(self.merge(base, custom, upstream), upstream)

    def test_dependency_edge_and_unrelated_upstream_package_both_survive(self):
        keep = package('keep', '1.0.0', source='registry+fixture')
        hook = package('hook', '2.0.0', source='registry+fixture', checksum='a' * 64)
        base = lock(package('codex-demo', '0.0.0', dependencies=('keep',)), keep, hook)
        custom = lock(package('codex-demo', WORKSPACE_VERSION, dependencies=('keep', 'hook')), keep, hook)
        upstream = base + package('new-upstream', '3.0.0', source='registry+fixture')
        result = tomllib.loads(self.merge(base, custom, upstream))['package']
        self.assertEqual(result[0]['version'], '0.0.0')
        self.assertEqual(result[0]['dependencies'], ['keep', 'hook'])
        self.assertTrue(any(p['name'] == 'new-upstream' for p in result))

    def test_competing_external_version_and_pin_changes_are_reported(self):
        base = lock(package('engine', '1.0.0', source='registry+fixture', checksum='a' * 64))
        custom = lock(package('engine', '1.1.0', source='registry+fixture', checksum='b' * 64))
        upstream = lock(package('engine', '1.2.0', source='registry+fixture', checksum='c' * 64))
        with self.assertRaises(LockfileMergeConflict) as caught:
            self.merge(base, custom, upstream)
        text = caught.exception.merged_text
        self.assertIn('<<<<<<< upstream', text)
        self.assertIn('>>>>>>> custom', text)
        self.assertIn('1.1.0', text)
        self.assertIn('1.2.0', text)

    def test_non_workspace_path_package_version_is_not_normalized(self):
        base = lock(package('outside', '0.0.0'))
        custom = lock(package('outside', WORKSPACE_VERSION))
        self.assertEqual(self.merge(base, custom, base), custom)

    def test_source_present_entry_is_not_normalized_even_with_workspace_name(self):
        base = lock(package('codex-demo', '0.0.0', source='registry+fixture'))
        custom = lock(package('codex-demo', WORKSPACE_VERSION, source='registry+fixture'))
        self.assertEqual(self.merge(base, custom, base), custom)

    def test_new_workspace_member_has_no_invented_base_version(self):
        base = lock()
        custom = lock(package('codex-demo', WORKSPACE_VERSION))
        self.assertEqual(self.merge(base, custom, base), custom)

    def test_non_generated_workspace_version_change_is_preserved(self):
        base = lock(package('codex-demo', '0.0.0'))
        custom = lock(package('codex-demo', '9.0.0'))
        self.assertEqual(self.merge(base, custom, base), custom)


if __name__ == '__main__':
    unittest.main()
